import { LEVEL_COLS, LEVEL_ROWS, tilesFromRows, type PlayableLevelData } from './level-data.ts';
import { buildLevel, type Level } from './level.ts';

/** A level that ships with the game rather than being made by a player. */
export interface BuiltinLevel {
  slug: string;
  name: string;
  data: PlayableLevelData;
}

function classic(
  rows: readonly string[],
  objects: Omit<PlayableLevelData, 'cols' | 'rows' | 'tiles'>,
): PlayableLevelData {
  return { cols: LEVEL_COLS, rows: LEVEL_ROWS, tiles: tilesFromRows(rows), ...objects };
}

